#!/bin/sh
# OpenWrt / BusyBox ash: 拉取订阅、识别格式、保留上次成功文件、生成 provider 覆写模块。
# 注意：此脚本不把不同格式强行拼成同一个 YAML；Mihomo 分别读取各 provider。
set -eu
umask 077
BASE=/etc/openclash
CFG="$BASE/aggregator/subscriptions.txt"
OUT="$BASE/proxy_provider"
MODULE="$BASE/overwrite/node_sources.conf"
mkdir -p "$OUT" "$BASE/overwrite"
[ -f "$CFG" ] || { echo "Missing $CFG" >&2; exit 1; }
command -v curl >/dev/null || { echo 'Please install curl' >&2; exit 1; }
LOCK="$BASE/aggregator/.update.lock"
if ! mkdir "$LOCK" 2>/dev/null; then echo 'Already running (or stale lock)' >&2; exit 1; fi
trap 'rm -rf "$LOCK"' EXIT HUP INT TERM
TMPMODULE="$MODULE.tmp.$$"
cat > "$TMPMODULE" <<'EOF'
# AUTO-GENERATED by /etc/openclash/aggregator/update.sh
# OpenClash overwrite module; do not select as main config
[YAML]
proxy-providers:
  manual_nodes:
    type: file
    path: ./proxy_provider/manual_nodes.yaml
    health-check:
      enable: true
      url: https://www.gstatic.com/generate_204
      interval: 300
      expected-status: 204
EOF
fail=0
count=0
while IFS='|' read -r name url fmt || [ -n "${name:-}" ]; do
  case "$name" in ''|\#*) continue;; esac
  case "$name" in *[!a-zA-Z0-9_-]*) echo "Invalid name: $name" >&2; fail=1; continue;; esac
  [ "$name" != manual_nodes ] || { echo 'Reserved name manual_nodes' >&2; fail=1; continue; }
  case "$url" in https://*) ;; *) echo "HTTPS URL required: $name" >&2; fail=1; continue;; esac
  case "${fmt:-auto}" in auto|yaml|uri|base64) ;; *) echo "Invalid format: $name" >&2; fail=1; continue;; esac
  file="$OUT/$name.yaml"
  tmp="$file.tmp.$$"
  if ! curl -fLsS --connect-timeout 15 --max-time 120 --retry 2 -A 'clash.meta' -o "$tmp" "$url"; then
    echo "Download failed: $name (old copy kept)" >&2; rm -f "$tmp"; fail=1
  elif [ ! -s "$tmp" ] || grep -Eiq '<!doctype html|<html|<body|<head' "$tmp"; then
    echo "Invalid/empty response: $name (old copy kept)" >&2; rm -f "$tmp"; fail=1
  else
    # YAML provider requires a top-level proxies key; Base64 and URI providers are supported by Mihomo.
    # This is a lightweight check, NOT full semantic/protocol validation.
    valid=0
    if grep -Eq '^proxies:[[:space:]]*$' "$tmp"; then valid=1
    elif grep -Eq '^(ss|ssr|vmess|vless|trojan|hysteria2|hy2|tuic)://' "$tmp"; then valid=1
    elif tr -d '\r\n ' < "$tmp" | base64 -d 2>/dev/null | grep -Eq '^(ss|ssr|vmess|vless|trojan|hysteria2|hy2|tuic)://'; then valid=1
    fi
    if [ "$valid" -eq 1 ]; then
      chmod 600 "$tmp"; mv -f "$tmp" "$file"; echo "Updated: $name"
    else
      echo "Unrecognized subscription: $name (old copy kept)" >&2; rm -f "$tmp"; fail=1
    fi
  fi
  # 只有本地文件存在时才加入模块，避免单个订阅失败导致整个配置无效。
  if [ -s "$file" ]; then
    cat >> "$TMPMODULE" <<EOF
  $name:
    type: file
    path: ./proxy_provider/$name.yaml
    health-check:
      enable: true
      url: https://www.gstatic.com/generate_204
      interval: 300
      expected-status: 204
EOF
    count=$((count+1))
  fi
done < "$CFG"
chmod 600 "$TMPMODULE"

# ------------------------------------------------------------------
# 安装前校验：坏的 YAML 绝不能被安装成生效模块
#
# 历史上此处出过事故：heredoc 的 $name 缩进写成 3 空格，比 header 里
# manual_nodes 的 2 空格深一级，整份 node_sources.conf YAML 解析失败，
# OpenClash 应用覆写模块失败导致全部节点消失。当时若此关卡存在，
# 坏文件会被拦在这里、旧模块继续生效，零宕机。
#
# 只做不依赖 ruby/opkg 的结构检查：所有 provider 顶层键必须与
# header 的 manual_nodes 同为 2 空格缩进。
# ------------------------------------------------------------------
if grep -qE '^   [A-Za-z0-9_-]+:' "$TMPMODULE"; then
  echo "FATAL: generated YAML has provider keys at wrong indent (3 spaces)." >&2
  echo "       Keeping previous node_sources.conf untouched." >&2
  grep -nE '^   [A-Za-z0-9_-]+:' "$TMPMODULE" | head -3 >&2
  rm -f "$TMPMODULE"
  exit 1
fi

# 每个 provider 必须带齐关键字段
for k in "type: file" "expected-status: 204"; do
  got=$(grep -c "$k" "$TMPMODULE")
  want=$((count + 1))
  if [ "$got" -lt "$want" ]; then
    echo "FATAL: expected >=${want} occurrences of '$k', got $got." >&2
    echo "       Keeping previous node_sources.conf untouched." >&2
    rm -f "$TMPMODULE"
    exit 1
  fi
done

if [ -f "$MODULE" ]; then
  cp -f "$MODULE" "$MODULE.bak"
fi
if [ -f "$MODULE" ] && cmp -s "$TMPMODULE" "$MODULE"; then
  rm -f "$TMPMODULE"
else
  mv -f "$TMPMODULE" "$MODULE"
  echo 'Updated node_sources.conf'
fi
echo "Active subscription providers: $count; manual_nodes: 1"
[ "$fail" -eq 0 ] || exit 1
